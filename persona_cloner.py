    last_char = [t.rstrip()[-1:] for t in clean if t.strip()]
    tcount = Counter(toks)
    pron = {k: sum(tcount[w] for w in v) for k, v in PRONOUNS.items()}
    ptot = sum(pron.values())
    pron_pct = {k: (r2(100 * v / ptot, 1) if ptot else 0) for k, v in pron.items()}

