def parse_whatsapp(path, target_name=None, default_year=DEFAULT_YEAR):
    if not os.path.exists(path):
        raise FileNotFoundError(f"File tidak ditemukan: {path}")
    rows, cur = [], None
    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.rstrip("\n")
            m = MSG_RE.match(line)
            if m:
                if cur:
                    rows.append(cur)
                g = m.groupdict()
                y = int(g["y"]) if g["y"] else default_year
                if g["y"] and len(g["y"]) == 2:
                    y += 2000
                dt = pd.Timestamp(year=y, month=int(g["m"]), day=int(g["d"]),
                                  hour=int(g["H"]), minute=int(g["M"]),
                                  second=int(g["S"] or 0))
                cur = {"datetime": dt, "raw_sender": g["sender"].strip(),
                       "text": g["text"]}
            elif SYS_RE.match(line) or line.strip() == "":
                continue                        # baris sistem / kosong dibuang
            elif cur is not None:
                cur["text"] += "\n" + line      # lanjutan pesan multiline
        if cur:
            rows.append(cur)

    df = pd.DataFrame(rows)
    if df.empty:
        raise ValueError("Tidak ada pesan yang berhasil diparse. Cek format file.")

    df["datetime"] = pd.to_datetime(df["datetime"])
    df = df.sort_values("datetime").reset_index(drop=True)

    # --- pisahkan pesan media / terhapus, catat jumlahnya per pengirim ---
    df["is_media"] = df.text.apply(lambda t: bool(MEDIA_RE.search(str(t))) and len(str(t)) < 80)
    media_counts = df[df.is_media].raw_sender.value_counts().to_dict()
    df = df[~df.is_media].reset_index(drop=True)

    # --- labeling TARGET vs LAWAN (satu breakout) ---
    df["sender"] = df["raw_sender"].apply(
        lambda s: "TARGET" if (target_name and s.strip() == target_name) else "LAWAN")

    # --- deidentifikasi isi teks: nama TARGET -> {{char}}, lawan -> {{user}} ---
    others = [s for s in df.raw_sender.unique() if s.strip() != target_name]
    user_name = Counter(df[df.sender == "LAWAN"].raw_sender).most_common(1)
    user_name = user_name[0][0] if user_name else None
    third = [s for s in others if s != user_name] + list(THIRD_PARTY_NAMES)

    def _scrub(t):
        t = str(t)
        t = re.sub(r"\+?\d[\d\s\-]{7,}\d", "<NOMOR>", t)      # nomor telepon
        for nm in sorted(third, key=len, reverse=True):        # pihak ketiga dulu
            if nm.strip():
                t = re.sub(rf"\b{re.escape(nm)}\b", "<NAMA>", t, flags=re.I)
        if user_name:
            t = re.sub(rf"\b{re.escape(user_name)}\b", "{{user}}", t, flags=re.I)
        if target_name:
            t = re.sub(rf"\b{re.escape(target_name)}\b", "{{char}}", t, flags=re.I)
        t = re.sub(r"@\w+", "<NAMA>", t)                       # mention
        return t

    df["text"] = df["text"].apply(_scrub)
    return df, media_counts


