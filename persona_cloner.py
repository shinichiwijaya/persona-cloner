def _meta_dari_nama(path):
    """Ambil tahun dan petunjuk tanggal dari nama berkas, mis. '06 Oktober 2026'."""
    name = os.path.basename(path).lower()
    th = re.search(r"(20\d{2})", name)
    year = int(th.group(1)) if th else None
    hint = None
    m = re.search(r"(\d{1,2})\s+([a-z]+)", name)
    if m and m.group(2) in BULAN:
        d, mo = int(m.group(1)), BULAN[m.group(2)]
        if d <= 12 and mo <= 12:
            hint = (d, mo)
    return year, hint

def _norm_time(t):
    """18.32 -> 18:32 ; 6:32:00 PM -> 18:32:00 ; am/pm dihitung."""
    t = re.sub(r"\s+", "", (t or "").replace("\u202f", ""))
    m = re.match(r"^(\d{1,2})[.:](\d{2})(?:[.:](\d{2}))?([AaPp]\.?[Mm]\.?)?$", t)
    if not m:
        return ""
    h, mi, sec, ap = int(m.group(1)), m.group(2), m.group(3), m.group(4)
    if ap:
        ap = ap.replace(".", "").lower()
        if ap == "pm" and h < 12:
            h += 12
        if ap == "am" and h == 12:
            h = 0
    return f"{h:02d}:{mi}" + (f":{sec}" if sec else "")

def _pisah(raw):
    return [int(x) for x in re.split(r"[-/.]", raw)]

def _deteksi_urutan(dates):
    f, s = [], []
    for d in dates:
        if not d:
            continue
        p = _pisah(d)
        if len(p) == 3 and p[0] > 99:
            return False, "tanggal diawali tahun (YYYY-MM-DD)"
        if len(p) >= 2:
            f.append(p[0]); s.append(p[1])
    if f and max(f) > 12:
        return True, "komponen pertama ada yang > 12"
    if s and max(s) > 12:
        return False, "komponen kedua ada yang > 12"
    return None, "ambigu (kedua komponen <= 12)"

def _ke_iso(raw, time, dayfirst, default_year):
    p = _pisah(raw) if raw else [1, 1]
    if len(p) == 3 and p[0] > 99:          # YYYY-MM-DD
        y, mo, d = p
    elif len(p) == 3:                      # DD/MM/YY atau MM/DD/YY
        a, b, y = p
        if y < 100:
            y += 2000 if y < 70 else 1900
        d, mo = (a, b) if dayfirst else (b, a)
    else:                                  # DD/MM tanpa tahun
        a, b = (p + [1, 1])[:2]
        d, mo = (a, b) if dayfirst else (b, a)
        y = default_year
    if not (1 <= mo <= 12):
        d, mo = mo, d
    return f"{y:04d}-{mo:02d}-{d:02d}" + (f" {time}" if time else "")

