def anonymize_text(t):
    t = (t or "").translate(ZERO_WIDTH)
    t, c = RE_URL.subn("<URL>", t);      MASK_LOG["<URL>"] += c
    t, c = RE_EMAIL.subn("<EMAIL>", t);  MASK_LOG["<EMAIL>"] += c
