def clean_profile(p):
    for grp in ("big_five", "dimensi_gaya"):
        g = p.get(grp) or {}
        for k, v in list(g.items()):
            v = v if isinstance(v, dict) else {"skor": v, "bukti": []}
            try:
                v["skor"] = max(0, min(100, int(round(float(v.get("skor", 50))))))
            except Exception:
                v["skor"] = 50
            v.setdefault("bukti", [])
            g[k] = v
        p[grp] = g
    return p

