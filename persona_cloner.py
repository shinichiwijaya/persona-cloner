def parse_whatsapp(path, dayfirst=None, default_sender="UNKNOWN", default_year=None):
    global MEDIA_COUNTS
    raw = open(path, encoding="utf-8", errors="ignore").read()
    for ch, rep in {"\u200e": "", "\u200f": "", "\ufeff": "", "\u202f": " ", "\u00a0": " "}.items():
        raw = raw.replace(ch, rep)
    lines = raw.splitlines()

    rows, cur, fmt = [], None, None
    for line in lines:
        m, rest, nama = None, None, None
        for nama, pat in HEADER_PATTERNS:
            mm = pat.match(line)
            if mm:
                m, rest = mm, mm.group("rest")
                break
        if m is not None:
            if cur:
                rows.append(cur)
            cur = None
            ms = RE_SENDER.match(rest)
            if not ms:                     # pesan sistem (tanpa pengirim)
                continue
            g = m.groupdict()
            cur = {"date": g.get("date") or "", "time": _norm_time(g.get("time") or ""),
                   "sender": ms.group(1).strip(), "text": ms.group(2)}
            fmt = fmt or nama
        elif cur is not None:              # lanjutan pesan multi-baris
            cur["text"] += "\n" + line
    if cur:
        rows.append(cur)

    if not rows:                           # salinan polos: tanpa tanggal dan jam
        fmt = "salinan polos (tanpa tanggal dan jam)"
        for line in lines:
            if not line.strip():
                continue
            ms = RE_SENDER.match(line)
            rows.append({"date": "", "time": "",
                         "sender": ms.group(1).strip() if ms else default_sender,
                         "text": ms.group(2) if ms else line})
    if not rows:
        raise ValueError("Tidak ada pesan terbaca. Buka file .txt, tempelkan 3 baris pertama ke chat.")

    df = pd.DataFrame(rows)

    year_name, hint = _meta_dari_nama(path)
    if default_year is None:
        default_year = year_name or pd.Timestamp.today().year
    tanpa_tahun = (df["date"].str.count(r"[-/.]") < 2).any()
    tanpa_tanggal = (df["date"] == "").any()

    if dayfirst is None:
        det, alasan = _deteksi_urutan(df["date"])
        if det is None and hint and df["date"].iloc[0]:
            a, b = _pisah(df["date"].iloc[0])[:2]
            d0, m0 = hint
            if (a, b) == (m0, d0):
                det, alasan = False, f"cocok dengan nama berkas ({d0} bulan {m0})"
            elif (a, b) == (d0, m0):
                det, alasan = True, f"cocok dengan nama berkas ({d0} bulan {m0})"
        if det is None:
            det, alasan = True, "ambigu, diasumsikan hari/bulan"
        dayfirst = det
        print(f"Urutan tanggal: {'hari/bulan' if dayfirst else 'bulan/hari'} ({alasan})")
    else:
        print(f"Urutan tanggal: {'hari/bulan' if dayfirst else 'bulan/hari'} (diatur manual)")

    stamps = [_ke_iso(r["date"], r["time"], dayfirst, default_year) for _, r in df.iterrows()]
    stamps = pd.Series(stamps, index=df.index)
    try:
        df["datetime"] = pd.to_datetime(stamps, format="mixed", errors="coerce")
    except (TypeError, ValueError):
        df["datetime"] = pd.to_datetime(stamps, errors="coerce")

    if tanpa_tahun:
        print(f"Peringatan: tahun tidak ada di berkas, dipakai tahun {default_year}.")
    if tanpa_tanggal:
        print("Peringatan: pesan tanpa tanggal. Tanggal diisi placeholder, "
              "sehingga fitur jeda balas dan inisiasi tidak valid.")
    if (df["time"] == "").any():
        print("Peringatan: sebagian/semua pesan tanpa jam. Fitur berbasis waktu tidak dapat dihitung.")

    bad = int(df["datetime"].isna().sum())
    if bad:
        print(f"Peringatan: {bad} baris dengan tanggal tidak terbaca dibuang.")
    df = df.dropna(subset=["datetime"])
    df["text"] = (df["text"].str.replace(r"\s*<(pesan ini diedit|this message was edited)>", "",
                                         regex=True, flags=re.I).str.strip())
    MEDIA_COUNTS = df[df["text"].apply(is_media)]["sender"].value_counts().to_dict()
    df = df[(df["text"] != "") & (~df["text"].apply(is_noise))]
    print(f"Format terbaca: {fmt}")
    return df[["datetime", "sender", "text"]].reset_index(drop=True)

def resolve_target(df, target_name):
    """Find the actual sender name in df matching target_name (case-insensitive)."""
    senders = df['sender'].unique()
    for s in senders:
        if s.lower() == target_name.lower():
            return s
    # Fallback to fuzzy match or first sender if not found
    for s in senders:
        if target_name.lower() in s.lower():
            return s
    raise ValueError(f"Target name '{target_name}' tidak ditemukan di daftar pengirim: {list(senders)}")

